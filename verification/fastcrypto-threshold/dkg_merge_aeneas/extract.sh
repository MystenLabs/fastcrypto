# Regenerates the Lean translation of `Party::merge` and the functions it calls, and records the
# hash of the code it was generated from in translated_code.sha256. See README.md.
#
# Needs `charon` and `aeneas` from the commits named in README.md, on PATH or in $CHARON and
# $AENEAS.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../../.." && pwd)"
CHARON="${CHARON:-charon}"
AENEAS="${AENEAS:-aeneas}"
LLBC="$HERE/dkg_merge_standins.llbc"

# Translate `Party::merge` and everything it calls (Charon follows the calls). The stand-in crate's
# build script copies the production code of the verified functions into it.
(
    cd "$HERE/standins"
    "$CHARON" cargo --preset=aeneas \
        --start-from 'dkg_merge_standins::Party::merge' \
        --dest-file "$LLBC"
)

# Generate DkgMerge/{Types,Funs}.lean (and a template for the external functions).
"$AENEAS" -backend lean -split-files -namespace DkgMerge \
    -dest "$HERE" -subdir DkgMerge "$LLBC"

# The generated files name the Rust source of each definition. Make those paths independent of
# where the repository is checked out and of the build directory.
for f in "$HERE"/DkgMerge/Types.lean "$HERE"/DkgMerge/Funs.lean "$HERE"/DkgMerge/FunsExternal_Template.lean; do
    sed -i.bak -e "s#$REPO/##g" \
        -e "s#target/[^']*/out/verified_regions\.rs#verified_regions.rs (generated by standins/build.rs)#g" \
        "$f"
    rm "$f.bak"
done

# Record which code the translation was generated from.
(cd "$REPO" && BLESS_AENEAS_TRANSLATION=1 cargo test -q -p fastcrypto-threshold --lib -- \
    --exact dkg_merge_aeneas_freshness_test::dkg_merge_lean_translation_is_fresh)

echo "Done. Now check the proofs with: (cd $HERE && lake build)"
